"""Add the full proof boards to the Phase 1 lessons that compare prepositions.

Run from prepositions-lab/:  python3 tools/content/proofs.py
For each comparison lesson: every preposition's picture and question, sentences proving why it fits
and why each other one does not, a how-to-choose board, and practice questions. The proof sets come
from atlas_pairs.py (shared with the sense atlas) and proofs_p1.py. Writes content/proofs.js, which
adds these steps to each lesson just before its summary step, so the hand-made boards stay as they are.
"""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
import atlas
exec(open(os.path.join(here, "atlas_data.py")).read(), atlas.__dict__)
exec(open(os.path.join(here, "atlas_pairs.py")).read(), atlas.__dict__)
exec(open(os.path.join(here, "proofs_p1.py")).read(), atlas.__dict__)

pair_pics = {it["id"]: {p: sp for p, sp, ex, cap in it["panels"]} for u in atlas.UNITS for it in u["items"] if it["kind"] == "pair"}
out = ["/* Proof boards for the Phase 1 comparison lessons: why this one and not the other, proved on sentences.",
       "   Generated by tools/content/proofs.py; edit the data in atlas_pairs.py and proofs_p1.py. */",
       "(function () {",
       "  const add = (id, steps) => {",
       "    const l = PLAB.lessons[id];",
       "    if (!l || l.steps.some((s) => s.id === steps[0].id)) return;",
       "    const at = l.steps.findIndex((s) => s.id === \"summary\");",
       "    l.steps.splice(at < 0 ? l.steps.length : at, 0, ...steps);",
       "  };"]
n = 0
jobs = [(lid, atlas.PAIRS[pid], pair_pics.get(pid, {})) for lid, pid in atlas.P1_FROM_ATLAS.items()]
jobs += [(lid, pr, pr["pics"]) for lid, pr in atlas.P1_PROOFS.items()]
for lid, proof, pics in jobs:
    title = " and ".join(p.upper() for p in proof["order"])
    intro = dict(id="pv-intro", title=f"Prove it: {title}",
                 alt=f"Prove it: for each of {', '.join(proof['order'])}, its picture, the question to ask, and sentences where it is right and the others are wrong.",
                 says=[("Now we prove the difference. For each one: its picture, the question to ask yourself, and sentences where it is right and the others are wrong, with the reason for every one.", "pv-i1")],
                 actions=['PLAB.kit.clear("clear-pv-intro")',
                          f'{{ do: "write", id: "pv-i0", text: "Prove it", x: 480, y: 200, size: 60, ink: "accent", anchor: "middle" }}',
                          f'{{ do: "write", id: "pv-i1", text: {atlas.T("why " + " · ".join(proof["order"]) + ", and why not the other")}, x: 480, y: 290, size: 32, ink: "accent2", anchor: "middle", fit: 900 }}',
                          '{ do: "write", id: "pv-i2", text: "picture · question · proof on sentences · how to choose", x: 480, y: 350, size: 24, ink: "muted", anchor: "middle", fit: 900 }'])
    steps, checks = atlas.proof_steps(title, proof, pics, "pv-", f"{lid}-pv")
    steps = [intro] + steps
    for j, (p, ck) in enumerate(checks, 1):
        steps.append(dict(id=f"pv-practice-{j}", title=f"Prove it, practice {j}", alt="The last board stays.",
                          says=[("Which one fits? Picture the situation, ask the question, then choose.", None)], actions=[], check=ck))
    out.append(f"  add({atlas.T(lid)}, [\n{atlas.js_steps(steps)}\n  ]);")
    n += 1
out.append("})();\n")
open("content/proofs.js", "w").write("\n".join(out))
print("proof boards added to", n, "lessons")
