"""Past-tense boards for every time lesson outside Phase 8: writes content/past.js, which splices
"In the past" boards into each lesson before its summary. Data: PAST_OTHER in past_data.py.
Run from prepositions-lab/:  python3 tools/content/past.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from past_data import PAST_OTHER, MOVE

T = lambda v: json.dumps(v, ensure_ascii=False)
cap = lambda s: s[0].upper() + s[1:]

def board(n, title, rows, kind="past"):
    tag = f"pt{n}" if kind == "past" else f"mv{n}"
    rs = ", ".join(f"[{T(p)}, {T(t)}, {{ hl: {T(h)}, sub: {T(s)}, size: 30 }}]" for p, t, h, s in rows)
    say = [dict(text=f"_{t}_ {cap(s)}.", cue=f"{tag}r{i + 1}") for i, (p, t, h, s) in enumerate(rows)]
    return f"""      {{
        id: {T(f"{kind}-{n}")},
        title: {T(title)},
        alt: {T(title + ". " + " ".join(f"{t} {cap(s)}." for p, t, h, s in rows))},
        say: {T([dict(text="Now the same words in past sentences. Watch what the past tense changes." if kind == "past" else "One more test: does something MOVE to the place, or is it just AT the spot?", cue=f"{tag}-t")] + say)},
        actions: [
          PLAB.kit.clear({T("clear-" + tag)}),
          {{ do: "write", id: {T(tag + "-t")}, text: {T(title)}, x: 480, y: 50, size: 32, ink: "accent", anchor: "middle", fit: 900 }},
          ...PLAB.kit.rows({T(tag + "r")}, [{rs}], {{ y: 135, gap: 135 }}),
        ],
      }}"""

out = ["/* Past-tense boards for the time lessons. Generated by tools/content/past.py; edit past_data.py. */",
       "(function () {", "  const add = (id, steps) => {", "    const l = PLAB.lessons[id];",
       "    if (!l || l.steps.some((s) => s.id === steps[0].id)) return;",
       '    let at = l.steps.findIndex((s) => s.id === "summary" || s.id.startsWith("practice"));',
       "    l.steps.splice(at < 0 ? l.steps.length : at, 0, ...steps);", "  };"]
for lid, boards in PAST_OTHER.items():
    out.append(f"  add({T(lid)}, [\n" + ",\n".join(board(i + 1, t, r) for i, (t, r) in enumerate(boards)) + "\n  ]);")
for lid, boards in MOVE.items():
    out.append(f"  add({T(lid)}, [\n" + ",\n".join(board(i + 1, t, r, "move") for i, (t, r) in enumerate(boards)) + "\n  ]);")
out.append("})();\n")
open("content/past.js", "w").write("\n".join(out))
print(len(PAST_OTHER), "lessons,", sum(len(b) for b in PAST_OTHER.values()), "past boards")
