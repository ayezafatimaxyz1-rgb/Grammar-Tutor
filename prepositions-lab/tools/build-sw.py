"""Write sw.js: the offline cache for the home-screen app. Run after adding or changing lessons:
python3 tools/build-sw.py   (from prepositions-lab/)"""
import hashlib, re
html = open("index.html").read()
files = ["./", "index.html", "manifest.webmanifest", "css/app.css", "icons/icon-192.png", "icons/icon-512.png"]
files += re.findall(r'<script src="([^"]+)"', html)
h = hashlib.sha1()
for f in files[1:]:
    h.update(open(f, "rb").read())
version = h.hexdigest()[:10]
open("sw.js", "w").write(f"""/* Offline cache for the home-screen app. Generated by tools/build-sw.py; do not edit by hand. */
const CACHE = "prepositions-lab-{version}";
const FILES = {files!r};

self.addEventListener("install", (e) => {{
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
}});

self.addEventListener("activate", (e) => {{
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
}});

// App files come from the cache, so the app works offline; Google Fonts are cached the first time they load.
self.addEventListener("fetch", (e) => {{
  if (e.request.method !== "GET") return;
  e.respondWith(
    caches.match(e.request, {{ ignoreSearch: true }}).then((hit) => hit || fetch(e.request).then((res) => {{
      if (res.ok && /fonts\\.(googleapis|gstatic)\\.com/.test(e.request.url)) {{
        const copy = res.clone();
        caches.open(CACHE).then((c) => c.put(e.request, copy));
      }}
      return res;
    }}))
  );
}});
""".replace("'", '"'))
print(len(files), "files, cache", version)
