"""Write sw.js: the offline cache for the home-screen app. Run after adding or changing lessons:
python3 tools/build-sw.py   (from prepositions-lab/)"""
import hashlib, re
html = open("index.html").read()
files = ["./", "index.html", "manifest.webmanifest", "css/app.css", "icons/icon-192.png", "icons/icon-512.png"]
files += re.findall(r'<script src="([^"]+)"', html)
files += ["js/vendor/jspdf.umd.min.js", "js/vendor/kalam-font.js"]  # loaded only when a notes PDF is made
h = hashlib.sha1()
for f in files[1:]:
    h.update(open(f, "rb").read())
version = h.hexdigest()[:10]
open("sw.js", "w").write(f"""/* Offline cache for the home-screen app. Generated by tools/build-sw.py; do not edit by hand.
   Online, every file comes fresh from the network (so updates show at once) and the copy is saved;
   offline, the saved copy is used. */
const CACHE = "prepositions-lab-{version}";
const FILES = {files!r};

self.addEventListener("install", (e) => {{
  // cache: "reload" skips the browser's own HTTP cache, so an update never saves an old file.
  e.waitUntil(caches.open(CACHE).then((c) => Promise.all(FILES.map((f) => fetch(new Request(f, {{ cache: "reload" }})).then((r) => r.ok && c.put(f, r))))).then(() => self.skipWaiting()));
}});

self.addEventListener("activate", (e) => {{
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
}});

self.addEventListener("fetch", (e) => {{
  if (e.request.method !== "GET") return;
  e.respondWith(
    fetch(e.request, {{ cache: "no-cache" }})
      .then((res) => {{
        if (res.ok) {{
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(e.request, copy));
        }}
        return res;
      }})
      .catch(() => caches.match(e.request, {{ ignoreSearch: true }}).then((hit) => hit || caches.match("index.html")))
  );
}});
""".replace("'", '"'))
print(len(files), "files, cache", version)
