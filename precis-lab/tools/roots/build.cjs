// Reads tools/roots/src*.txt and the app's word lists, writes content/roots.js (explicit membership).
const fs = require("fs"), path = require("path");
const dir = __dirname;
const words = fs.readFileSync(path.join(dir, "allwords.txt"), "utf8").split("\n").filter(Boolean);
const rows = [];
fs.readdirSync(dir).filter((f) => /^src.*\.txt$/.test(f)).sort().forEach((f) =>
  fs.readFileSync(path.join(dir, f), "utf8").split("\n").forEach((l) => {
    if (!l.trim() || l.startsWith("#")) return;
    const p = l.split("|").map((x) => x.trim());
    if (p.length < 5) return console.error("BAD", l);
    rows.push({ kind: p[0], stems: p[1].split(",").map((s) => s.trim()).filter(Boolean), form: p[2], origin: p[3], meaning: p[4], extra: (p[5] || "").split(",").map((s) => s.trim()).filter(Boolean), out: (p[6] || "").split(",").map((s) => s.trim()).filter(Boolean) });
  })
);
const PRE = "un in im ir il dis mis non re de over under counter anti pre pro sub sup suc suf sus con com col cor co ex e ef inter intro trans ad ac af ag al ap ar as at a ab abs ob oc of op per mal bene super sur circum contra be en em".split(" ");
function heads(w) {
  const out = [w];
  let cur = [w];
  for (let i = 0; i < 2; i++) {
    const nxt = [];
    cur.forEach((c) => PRE.forEach((p) => c.startsWith(p) && c.length - p.length >= 4 && nxt.push(c.slice(p.length))));
    nxt.forEach((x) => out.push(x));
    cur = nxt;
  }
  return out;
}
const out = [];
rows.forEach((r, i) => {
  const mem = words.filter((w) => {
    if (r.out.some((o) => (o.endsWith("-x") ? w === o.slice(0, -2) : w.includes(o)))) return false;
    return r.stems.some((s) => {
      if (r.kind === "P") return w.startsWith(s) && w.length >= s.length + 3;
      if (r.kind === "S") return w.endsWith(s) && w.length >= s.length + 3;
      return heads(w).some((h) => h.startsWith(s));
    });
  });
  r.members = mem;
});
const report = process.argv.includes("--report");
if (report) rows.forEach((r) => console.log(`${r.kind} ${r.form} (${r.members.length}): ${r.members.join(" ")}`));
const covered = new Set(rows.flatMap((r) => r.members));
console.error(`roots ${rows.length}, words covered ${covered.size} of ${words.length}`);
if (process.argv.includes("--uncovered")) fs.writeFileSync(path.join(dir, "uncovered.txt"), words.filter((w) => !covered.has(w)).join("\n"));
const data = rows.map((r) => [r.kind, r.form, r.origin, r.meaning, r.members, r.extra.filter((e) => !r.members.includes(e.toLowerCase()))]);
fs.writeFileSync(path.join(dir, "../../content/roots.js"), "/* Generated by tools/roots/build.cjs: roots, prefixes and suffixes with their family words. Do not edit by hand. */\nPLAB.roots = " + JSON.stringify(data) + ";\n");
