const fs=require("fs");
const W=fs.readFileSync(__dirname+"/allwords.txt","utf8").split("\n").filter(Boolean);
const SET=new Set(W);
const PRE=["un","in","im","ir","il","dis","mis","non","re","de","over","under","counter","anti","self"];
const SUF=["fulness","lessness","ization","isation","ational","ations","ation","ition","ition","ments","ment","ness","ities","ity","ively","ive","ious","ous","ably","ibly","able","ible","ally","ful","less","ically","ical","ic","ism","ist","ize","ise","ify","ance","ence","ancy","ency","ant","ent","ing","ed","ly","er","or","al","ion","s","y","e"];
function stems(w){
  const out=new Set([w]);let cur=[w];
  for(let round=0;round<3;round++){const nxt=[];
    for(const c of cur){
      for(const s of SUF)if(c.endsWith(s)&&c.length-s.length>=4){nxt.push(c.slice(0,-s.length));}
      for(const p of PRE)if(c.startsWith(p)&&c.length-p.length>=5){nxt.push(c.slice(p.length));}
    }
    nxt.forEach(x=>{const y=x.replace(/(i|e|y)$/,"");if(y.length>=4){out.add(y)}});cur=nxt;}
  return out;}
// union-find on shared stems of length>=5 (or equal)
const par={};const f=x=>par[x]===x?x:(par[x]=f(par[x]));W.forEach(w=>par[w]=w);
const by={};W.forEach(w=>stems(w).forEach(s=>{if(s.length>=5||s===w)(by[s]=by[s]||[]).push(w)}));
Object.values(by).forEach(a=>{for(let i=1;i<a.length;i++)par[f(a[i])]=f(a[0])});
const g={};W.forEach(w=>(g[f(w)]=g[f(w)]||[]).push(w));
const DETACH=new Set("deliberate deliberation default faultless faulty important imported imports despondent respond insight oversight unsightly discrimination found founder unfounded recover recovery uncover undercover complicity allegiance allegory allege countless inferior inference deference demobilization demobilize mushroom mushrooming".split(" "));
const fam=Object.values(g).map(a=>a.filter(w=>!DETACH.has(w))).filter(a=>a.length>1&&a.length<=14).map(a=>a.sort());
require("fs").writeFileSync(__dirname+"/../../content/family.js","/* Generated by tools/roots/fam.cjs: words in the app that share a stem. */\nPLAB.families = "+JSON.stringify(fam)+";\n");
