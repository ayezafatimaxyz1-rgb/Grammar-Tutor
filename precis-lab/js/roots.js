/* Roots and word families.
   Tap any word marked with a dotted underline to see where it comes from and which words share its root.
   Data: PLAB.roots (content/roots.js) and PLAB.families (content/family.js), both generated by tools/roots. */
(function () {
  const P = window.PLAB;
  const norm = (s) => String(s || "").toLowerCase().trim();
  const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

  const PREFIX = { un: "not", in: "not, or into", im: "not, or into", ir: "not", il: "not", dis: "apart, not", mis: "wrongly", non: "not", re: "again, back", de: "down, away", over: "too much", under: "too little", anti: "against", self: "of oneself", pre: "before", sub: "under", out: "beyond" };
  const SUFFIX = { ness: "makes a noun: the state of being", ity: "makes a noun: a quality", ion: "makes a noun: an act or result", ation: "makes a noun: an act or result", ment: "makes a noun: a result", ly: "makes an adverb: in this way", ous: "makes an adjective: full of", ive: "makes an adjective: tending to", al: "makes an adjective: relating to", ic: "makes an adjective: relating to", ful: "makes an adjective: full of", less: "makes an adjective: without", able: "makes an adjective: can be done", ible: "makes an adjective: can be done", ize: "makes a verb: to make", ise: "makes a verb: to make", ify: "makes a verb: to make", ism: "makes a noun: a belief or system", ist: "makes a noun: a person who does it", ance: "makes a noun: a state", ence: "makes a noun: a state", ant: "a person or doing word", ent: "a person or doing word", ed: "past or adjective", ing: "doing, or adjective", er: "a person who does", or: "a person who does", y: "makes an adjective: full of" };

  let idx = null;
  function build() {
    if (idx) return idx;
    idx = { roots: new Map(), fam: new Map() };
    (P.roots || []).forEach((r, i) => r[4].forEach((w) => {
      if (!idx.roots.has(w)) idx.roots.set(w, []);
      idx.roots.get(w).push(i);
    }));
    (P.families || []).forEach((f, i) => f.forEach((w) => idx.fam.set(w, i)));
    return idx;
  }

  const known = (w) => build().roots.has(w) || build().fam.has(w);
  const posOf = (w) => (P.dict && P.dict[w] && P.dict[w].pos) || "";
  const isHeadword = (w) => (P.words || []).some((h) => norm(h.word) === w);

  // Affix hints: only when the base word is in the same family, so they are never guesses.
  function affixHints(w) {
    const i = build().fam.get(w);
    const group = i == null ? [] : P.families[i];
    const out = [];
    const has = (x) => group.includes(x) || group.includes(x + "e") || group.includes(x.replace(/i$/, "y"));
    Object.keys(PREFIX).forEach((p) => {
      if (w.startsWith(p) && w.length - p.length >= 4 && has(w.slice(p.length))) out.push({ part: p + "-", note: PREFIX[p], base: w.slice(p.length) });
    });
    Object.keys(SUFFIX).forEach((s) => {
      if (w.endsWith(s) && w.length - s.length >= 4 && (group.includes(w.slice(0, -s.length)) || group.includes(w.slice(0, -s.length) + "e") || group.includes(w.slice(0, -s.length) + "y"))) out.push({ part: "-" + s, note: SUFFIX[s], base: w.slice(0, -s.length) });
    });
    return out.slice(0, 3);
  }

  const chip = (w, cls = "") => `<button type="button" class="rchip ${cls}" data-root="${esc(w)}">${esc(w)}</button>`;

  /* ---------- the pencil sketch ---------- */
  const COLORS = ["#d9480f", "#1971c2", "#2f9e44", "#9c36b5"];
  function rng(seed) {
    let h = 2166136261;
    for (const ch of seed) h = Math.imul(h ^ ch.charCodeAt(0), 16777619);
    return () => ((h = Math.imul(h ^ (h >>> 15), 2246822507) >>> 0) / 4294967296);
  }
  const pieces = (form) => String(form).split(/[\/,]/).map((x) => x.replace(/\(.*?\)/g, "").replace(/-/g, "").trim().toLowerCase()).filter((x) => x.length >= 2).sort((a, b) => b.length - a.length);
  // Where the root's letters sit inside a word.
  function locate(word, form) {
    for (const p of pieces(form)) {
      const i = word.indexOf(p);
      if (i >= 0) return { i, len: p.length, piece: p };
    }
    return null;
  }
  const wrap = (t, n) => {
    const out = [];
    let line = "";
    String(t).split(" ").forEach((w) => {
      if ((line + " " + w).trim().length > n && line) { out.push(line); line = w; } else line = (line + " " + w).trim();
    });
    if (line) out.push(line);
    return out;
  };
  function meaningOf(w) {
    const h = (P.words || []).find((x) => norm(x.word) === w);
    if (h && h.senses[0]) return h.senses[0].sense;
    for (const pg of [P.themesPage, P.contextsPage]) {
      const e = pg && pg.entries && pg.entries().find((x) => norm(x.w) === w);
      if (e) return e.best;
    }
    return (P.glosses && P.glosses[w]) || "";
  }
  function pick(list, n) {
    if (list.length <= n) return list;
    const a = [...list].sort();
    return Array.from({ length: n }, (_, k) => a[Math.floor((k * a.length) / n)]);
  }

  function sketch(word, rootIdx) {
    const W = 340, R = rng(word);
    const j = (v, a = 1.6) => v + (R() - 0.5) * a * 2;
    const roots = rootIdx.map((ri) => P.roots[ri]).map((r) => ({ r, loc: locate(word, r[1]) }));
    // choose up to two roots: those found inside the word first, in letter order
    const chosen = roots.filter((x) => x.loc).sort((a, b) => a.loc.i - b.loc.i).slice(0, 2);
    if (!chosen.length) roots.slice(0, 1).forEach((x) => chosen.push(x));
    let famOnly = false;
    if (!chosen.length) {
      const fi = build().fam.get(word);
      if (fi == null) return "";
      famOnly = true;
      chosen.push({ r: ["F", "family", "same base word", "words built from one base", P.families[fi], []], loc: null });
    }
    const n = chosen.length, cw = Math.min(W / n, 230), off = (W - cw * n) / 2;
    const fs = Math.min(34, Math.floor(300 / (word.length * 0.6))), adv = fs * 0.6;
    const wx = (W - word.length * adv) / 2;
    const cx = (i) => wx + adv * (i + 0.5);
    let d = "", t = "", delay = 0.1;
    const line = (path, color, w = 2.4, dash = false, extra = "") => {
      const del = Math.min((delay += 0.04), 1.4).toFixed(2);
      return `<path d="${path}" class="rp-line" style="animation-delay:${del}s" stroke="${color}" stroke-width="${w}" ${dash ? 'stroke-dasharray="4 5"' : 'pathLength="1"'} fill="none" ${extra}/>` +
        `<path d="${path}" class="rp-line rp-line2" style="animation-delay:${del}s" stroke="${color}" stroke-width="1" fill="none" transform="translate(.8,.9)" pathLength="1"/>`;
    };
    const box = (x, y, w, h, color) => {
      const p = [[x, y], [x + w, y], [x + w, y + h], [x, y + h]].map(([a, b]) => [j(a, 1.2), j(b, 1.2)]);
      return `M${p[0][0]} ${p[0][1] + 6} Q${p[0][0]} ${p[0][1]} ${p[0][0] + 8} ${p[0][1]} L${p[1][0] - 8} ${p[1][1]} Q${p[1][0]} ${p[1][1]} ${p[1][0]} ${p[1][1] + 6} L${p[2][0]} ${p[2][1] - 6} Q${p[2][0]} ${p[2][1]} ${p[2][0] - 8} ${p[2][1]} L${p[3][0] + 8} ${p[3][1]} Q${p[3][0]} ${p[3][1]} ${p[3][0]} ${p[3][1] - 6}Z`;
    };
    // the word on top, root letters coloured
    const colorAt = Array(word.length).fill(null);
    chosen.forEach((c, k) => c.loc && (c.color = COLORS[k], [...Array(c.loc.len)].forEach((_, q) => (colorAt[c.loc.i + q] = COLORS[k]))));
    chosen.forEach((c, k) => (c.color = c.color || COLORS[k]));
    if (famOnly) colorAt.fill(COLORS[0]);
    t += `<g class="rp-word" font-size="${fs}">` + [...word].map((ch, i) => `<text x="${cx(i)}" y="40" text-anchor="middle"${colorAt[i] ? ` fill="${colorAt[i]}" font-weight="700"` : ""}>${esc(ch)}</text>`).join("") + `</g>`;
    let bottoms = [];
    chosen.forEach((c, k) => {
      const col = c.color, cxk = off + cw * (k + 0.5), left = off + cw * k;
      const [, form, origin, meaning, members, extra] = c.r;
      const seg = c.loc ? { x1: wx + adv * c.loc.i, x2: wx + adv * (c.loc.i + c.loc.len) } : { x1: wx, x2: wx + word.length * adv };
      const sx = (seg.x1 + seg.x2) / 2;
      d += line(`M${seg.x1} ${j(50)} Q${sx} ${j(55, 2.4)} ${seg.x2} ${j(50)}`, col, 3);
      d += line(`M${sx} 55 C${sx} 72 ${cxk} 72 ${cxk} 96`, col, 2.2);
      const mLines = wrap(meaning, Math.max(12, Math.floor(cw / 7.2)));
      const big = c.loc ? c.loc.piece : String(form).split("/")[0].trim();
      const hb = 30 + mLines.length * 16 + 18;
      d += line(box(left + 8, 98, cw - 16, hb, col), col, 2.2);
      t += `<text x="${cxk}" y="122" text-anchor="middle" class="rp-form" fill="${col}">${esc(big)}</text>`;
      mLines.forEach((ln, q) => (t += `<text x="${cxk}" y="${140 + q * 16}" text-anchor="middle" class="rp-m">${esc(ln)}</text>`));
      t += `<text x="${cxk}" y="${98 + hb - 7}" text-anchor="middle" class="rp-o">${esc(origin)}</text>`;
      // family words hang from a trunk, the shared letters coloured
      const bb = 98 + hb, tx = left + 16;
      const inApp = pick(members.filter((x) => x !== word), 6), outs = [];
      const rows = [...inApp.map((w) => ({ w, out: false })), ...outs.map((w) => ({ w, out: true }))];
      const y0 = bb + 30;
      const maxc = Math.floor((cw - 40) / 5.4);
      const nl = (row) => (row.out ? 0 : Math.min(2, wrap(meaningOf(row.w.toLowerCase()) || '', maxc).length));
      const rowsY = [];
      rows.reduce((acc, row) => (rowsY.push(acc), acc + 26 + 13 * nl(row) + 8), y0);
      if (rows.length) d += line(`M${cxk} ${bb} C${cxk} ${bb + 14} ${tx} ${bb + 12} ${tx} ${y0 - 5} L${tx} ${rowsY[rows.length - 1] - 5}`, col, 2);
      const sz = Math.max(11, Math.min(15, (cw - 38) / (Math.max(...rows.map((r) => r.w.length), 6) * 0.52)));
      rows.forEach((row, q) => {
        const y = rowsY[q];
        d += line(`M${tx} ${y - 5} Q${tx + 6} ${y - 7} ${tx + 14} ${y - 5}`, col, 1.8, row.out);
        const loc = row.out ? null : locate(row.w.toLowerCase(), form);
        const body = loc
          ? `${esc(row.w.slice(0, loc.i))}<tspan fill="${col}" font-weight="700">${esc(row.w.slice(loc.i, loc.i + loc.len))}</tspan>${esc(row.w.slice(loc.i + loc.len))}`
          : esc(row.w);
        t += `<text x="${tx + 18}" y="${y}" font-size="${sz.toFixed(1)}" class="rp-fw${row.out ? " rp-out" : ""}"${row.out ? "" : ` data-root="${esc(row.w)}"`}>${body}</text>`;
        const mm = row.out ? "" : meaningOf(row.w.toLowerCase());
        if (mm) {
          const ls = wrap(mm, maxc).slice(0, 2);
          if (wrap(mm, maxc).length > 2) ls[1] = ls[1].replace(/\s+\S*$/, "") + "…";
          ls.forEach((ln, z) => (t += `<text x="${tx + 18}" y="${y + 14 + z * 13}" class="rp-wm">${esc(ln)}</text>`));
        }
      });
      bottoms.push(rows.length ? rowsY[rows.length - 1] + 26 + 13 * nl(rows[rows.length - 1]) : bb + 36);
      if (!rows.length) t += `<text x="${cxk}" y="${bb + 28}" text-anchor="middle" class="rp-wm">no other words with this root in the app yet</text>`;
    });
    const H = Math.max(...bottoms) + 6;
    return `<svg class="rp-svg" viewBox="0 0 ${W} ${H}" role="img" aria-label="Root and family of ${esc(word)}">
      <defs><filter id="rp-pencil" x="-5%" y="-5%" width="110%" height="110%"><feTurbulence type="fractalNoise" baseFrequency="0.035" numOctaves="2" seed="4" result="n"/><feDisplacementMap in="SourceGraphic" in2="n" scale="2.4"/></filter></defs>
      <g filter="url(#rp-pencil)" stroke-linecap="round" stroke-linejoin="round">${d}</g>${t}</svg>`;
  }

  function panelBody(word) {
    const tokens = norm(word).split(/[\s-]+/).filter(Boolean);
    const w = norm(word);
    const key = known(w) ? [w] : tokens.filter(known);
    let html = `<h2 class="rp-title">${esc(word)} <span class="pos">${esc(posOf(norm(word)))}</span></h2>`;
    const mean = meaningOf(w);
    const lit = P.literal && P.literal[w];
    if (lit) html += `<p class="rp-lit">Literally <i>&ldquo;${esc(lit)}&rdquo;</i>${mean ? ` &rarr; <b>${esc(mean)}</b>` : ""}</p>`;
    else if (mean) html += `<p class="rp-says">means: <b>${esc(mean)}</b></p>`;
    if (!key.length) {
      return html + `<p class="rp-none">No root is recorded for <b>${esc(word)}</b> yet.</p>
        <p class="muted small">Many everyday words come from Old English, not Latin or Greek, so they have no classical root. We also have not added every word. Roots and families are added all the time.</p>
        <p class="row-buttons"><a class="button small" href="#roots">Browse all roots</a></p>`;
    }
    key.slice(0, 2).forEach((k) => {
      if (key.length > 1) html += `<h3 class="rp-token">${esc(k)}</h3>`;
      const rs = build().roots.get(k) || [];
      html += sketch(k, rs);
      if (rs.length) {
        const parts = rs.map((ri) => P.roots[ri]).map((r) => ({ r, loc: locate(k, r[1]) })).filter((x) => x.loc).sort((a, b) => a.loc.i - b.loc.i).slice(0, 2).map((x) => `<b>${esc(x.loc.piece)}</b> = ${esc(x.r[3])}`);
        if (parts.length) html += `<p class="rp-gloss">Parts: ${parts.join("  +  ")}</p>`;
      }
      const all = [...new Set(rs.flatMap((ri) => P.roots[ri][4]))].filter((x) => x !== k);
      const fi = build().fam.get(k);
      const fam = fi != null ? P.families[fi].filter((x) => x !== k) : [];
      if (fam.length) html += `<section class="rp-fam"><h4>Same word family</h4><p class="chips">${fam.map((x) => chip(x, "rchip-fam")).join("")}</p></section>`;
      if (all.length > 7) html += `<details class="rp-more"><summary>All ${all.length} words with this root</summary><p class="chips">${all.map((x) => chip(x)).join("")}</p></details>`;
      const hints = affixHints(k);
      if (hints.length) html += `<section class="rp-aff"><h4>Parts</h4><ul>${hints.map((h) => `<li><b>${esc(h.part)}</b> ${esc(h.note)}, added to <b>${esc(h.base)}</b></li>`).join("")}</ul></section>`;
    });
    if (isHeadword(w)) html += `<p class="row-buttons"><a class="button small" href="#word-${encodeURIComponent(w)}">See synonyms and antonyms</a></p>`;
    return html;
  }

  let box = null, lastFocus = null;
  function close() {
    if (!box) return;
    box.remove();
    box = null;
    document.removeEventListener("keydown", onKey);
    if (lastFocus && document.contains(lastFocus)) lastFocus.focus();
  }
  const onKey = (e) => e.key === "Escape" && close();

  function open(word) {
    if (!box) {
      lastFocus = document.activeElement;
      box = document.createElement("div");
      box.className = "rp-overlay";
      box.innerHTML = `<div class="rp-sheet" role="dialog" aria-modal="true" aria-label="Root and word family"><button type="button" class="rp-close" aria-label="Close">×</button><div class="rp-body"></div></div>`;
      document.body.appendChild(box);
      box.addEventListener("click", (e) => {
        if (e.target === box || e.target.closest(".rp-close")) return close();
        const link = e.target.closest("a[href]");
        if (link) return close();
        const t = e.target.closest("[data-root]");
        if (t) {
          open(t.dataset.root);
          box.querySelector(".rp-sheet").scrollTop = 0;
        }
      });
      document.addEventListener("keydown", onKey);
    }
    box.querySelector(".rp-body").innerHTML = panelBody(word);
    box.querySelector(".rp-close").focus();
  }

  document.addEventListener("click", (e) => {
    if (box && box.contains(e.target)) return;
    const t = e.target.closest("[data-root]");
    if (t) {
      e.preventDefault();
      open(t.dataset.root);
    }
  });

  /* ---------- the Roots page ---------- */
  function renderRoots(app) {
    build();
    const roots = (P.roots || []).map((r, i) => ({ r, i })).filter((x) => x.r[4].length >= 2).sort((a, b) => a.r[1].localeCompare(b.r[1]));
    const card = ({ r }) => `<article class="root-card" data-s="${esc(norm(r[1] + " " + r[3] + " " + r[2] + " " + r[4].join(" ")))}">
      <h3><span class="rp-big">${esc(r[1])}</span> <span class="rp-mean">= ${esc(r[3])}</span></h3>
      <p class="muted small">${esc(r[2])}</p>
      <p class="chips">${r[4].slice(0, 30).map((x) => chip(x)).join("")}${r[4].length > 30 ? `<span class="muted small"> +${r[4].length - 30} more</span>` : ""}</p>
      ${r[5].length ? `<p class="chips">${r[5].slice(0, 10).map((x) => `<span class="rchip rchip-out">${esc(x)}</span>`).join("")}</p>` : ""}
    </article>`;
    app.innerHTML = `<section class="page-head">
        <p class="eyebrow">Roots and families</p>
        <h1>Roots, and the words that grow from them</h1>
        <p class="lede">Learn one root and you can read many words. ${roots.length} roots, each with the words from this app that use it. Tap any word to open its family. Words in grey are family members that are not in the app.</p>
        <label class="search"><span class="sr-only">Search roots</span><input type="search" id="rt-search" placeholder="Search a root, a meaning or a word, for example: law, dict, generous" autocomplete="off"></label>
      </section>
      <p class="muted small" id="rt-count"></p>
      <div id="rt-list" class="root-list">${roots.map(card).join("")}</div>`;
    const cards = [...app.querySelectorAll(".root-card")];
    const count = app.querySelector("#rt-count");
    app.querySelector("#rt-search").addEventListener("input", (ev) => {
      const q = norm(ev.target.value);
      let n = 0;
      cards.forEach((c) => {
        const show = !q || c.dataset.s.includes(q);
        c.hidden = !show;
        if (show) n++;
      });
      count.textContent = q ? `${n} ${n === 1 ? "root" : "roots"} match "${q}".` : "";
    });
  }

  P.roots_ui = { open, close, renderRoots, known, hasRoot: (w) => known(norm(w)) };
})();
